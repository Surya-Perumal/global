    <script>
        document.addEventListener('DOMContentLoaded', function () {
            // Mobile Menu Drawer
            const menuToggle = document.getElementById('mobile-menu-toggle');
            const menuClose = document.getElementById('mobile-menu-close');
            const mobileDrawer = document.getElementById('mobile-drawer');
            const overlay = document.getElementById('mobile-drawer-overlay');

            function toggleMenu() {
                mobileDrawer.classList.toggle('active');
                overlay.classList.toggle('active');
                document.body.style.overflow = mobileDrawer.classList.contains('active') ? 'hidden' : '';
            }

            menuToggle.addEventListener('click', toggleMenu);
            menuClose.addEventListener('click', toggleMenu);
            overlay.addEventListener('click', toggleMenu);

            // Sticky Header Shadow
            const header = document.getElementById('main-header');
            window.addEventListener('scroll', function () {
                if (window.scrollY > 10) {
                    header.classList.add('scrolled');
                } else {
                    header.classList.remove('scrolled');
                }
            });

            // Premium Auto-Changing Image Section Logic
            const pisContainer = document.getElementById('pis-slider-container');
            if (pisContainer) {
                const mainImage = document.getElementById('pis-main-image');
                const badgeText = document.getElementById('pis-badge-text');
                const badgeElement = document.getElementById('pis-badge');
                const dotsContainer = document.getElementById('pis-dots');
                const btnPrev = document.getElementById('pis-prev');
                const btnNext = document.getElementById('pis-next');
                const progressBar = document.getElementById('pis-progress');

                const slideData = [
                    { img: "https://images.unsplash.com/photo-1523240795612-9a054b0db644?q=80&w=800&auto=format&fit=crop", badge: "International Campus" },
                    { img: "https://images.unsplash.com/photo-1523050854058-8df90110c9f1?q=80&w=800&auto=format&fit=crop", badge: "Graduation Ceremonies" },
                    { img: "https://images.unsplash.com/photo-1517486808906-6ca8b3f04846?q=80&w=800&auto=format&fit=crop", badge: "Multicultural Groups" },
                    { img: "https://images.unsplash.com/photo-1541339907198-e08756dedf3f?q=80&w=800&auto=format&fit=crop", badge: "Modern Universities" },
                    { img: "https://images.unsplash.com/photo-1524850011238-e3d235c7d4c9?q=80&w=800&auto=format&fit=crop", badge: "Student Travel" }
                ];

                let currentSlide = 0;
                let sliderInterval;
                const SLIDE_DURATION = 5000;

                // Create Dots if container exists
                if (dotsContainer) {
                    slideData.forEach((_, i) => {
                        const dot = document.createElement('div');
                        dot.classList.add('pis-dot');
                        if (i === 0) dot.classList.add('active');
                        dot.addEventListener('click', () => goToSlide(i));
                        dotsContainer.appendChild(dot);
                    });
                }
                const dots = document.querySelectorAll('.pis-dot');

                function updateSlideContent(index) {
                    if (dotsContainer && dots.length > 0) {
                        dots.forEach(d => d.classList.remove('active'));
                        dots[index].classList.add('active');
                    }

                    if (mainImage) mainImage.classList.add('fade-out');
                    if (badgeElement) badgeElement.classList.add('fade-out');

                    setTimeout(() => {
                        if (mainImage) {
                            mainImage.src = slideData[index].img;
                            mainImage.classList.remove('fade-out');
                        }
                        if (badgeText && badgeElement) {
                            badgeText.textContent = slideData[index].badge;
                            badgeElement.classList.remove('fade-out');
                        }
                    }, 400); // match css transition
                }

                function resetProgress() {
                    if (!progressBar) return;
                    progressBar.style.transition = 'none';
                    progressBar.style.width = '0%';
                    setTimeout(() => {
                        progressBar.style.transition = `width ${SLIDE_DURATION}ms linear`;
                        progressBar.style.width = '100%';
                    }, 50);
                }

                function goToSlide(index) {
                    currentSlide = index;
                    updateSlideContent(currentSlide);
                    resetTimer();
                }

                function nextSlide() {
                    currentSlide = (currentSlide + 1) % slideData.length;
                    updateSlideContent(currentSlide);
                    resetProgress();
                }

                function prevSlide() {
                    currentSlide = (currentSlide - 1 + slideData.length) % slideData.length;
                    updateSlideContent(currentSlide);
                    resetTimer();
                }

                function resetTimer() {
                    clearInterval(sliderInterval);
                    resetProgress();
                    sliderInterval = setInterval(nextSlide, SLIDE_DURATION);
                }

                if (btnNext) btnNext.addEventListener('click', () => { nextSlide(); resetTimer(); });
                if (btnPrev) btnPrev.addEventListener('click', () => { prevSlide(); });

                // Pause on hover
                pisContainer.addEventListener('mouseenter', () => {
                    clearInterval(sliderInterval);
                    if (progressBar) {
                        const computedWidth = window.getComputedStyle(progressBar).width;
                        progressBar.style.transition = 'none';
                        progressBar.style.width = computedWidth;
                    }
                });

                pisContainer.addEventListener('mouseleave', () => {
                    resetTimer();
                });

                // Start Auto Slider
                resetTimer();
            }
        });
    </script>
